// Local demo deploy. Runs against the hardhat node started by scripts/local-demo.sh (chainId 31338).
// Does NOT touch deployments/portaldotTestnet.json or any portaldot config. Writes a separate local file only.
//
// Accounts (hardhat default keys, local chain only, no value):
//   #0 admin + watcher (keeper signer for the demo), #1 owner, #2 beneficiary, #3 beneficiary 2
// It deploys LastKey and two MockERC20 tokens, mints tokens to the owner, sets the owner's sweep approvals,
// creates a demo vault with beneficiaries, and writes frontend/local-config.js + scripts/local-demo.out.json.
const fs = require("fs");
const path = require("path");
const hre = require("hardhat");
const { ethers } = hre;

const ROOT = path.join(__dirname, "..");

async function main() {
  const net = await ethers.provider.getNetwork();
  if (net.chainId !== 31338n) throw new Error("local deploy must run on the hardhat node (chainId 31338), got " + net.chainId);

  const signers = await ethers.getSigners();
  const [admin, owner, ben1, ben2] = signers;

  const LK = await ethers.getContractFactory("LastKey");
  const lk = await LK.deploy();
  await lk.waitForDeployment();
  const lkAddr = await lk.getAddress();

  const M = await ethers.getContractFactory("MockERC20");
  const tokA = await M.deploy("Demo USD", "DUSD");
  await tokA.waitForDeployment();
  const tokB = await M.deploy("Demo Gold", "DGOLD");
  await tokB.waitForDeployment();
  const tokAAddr = await tokA.getAddress();
  const tokBAddr = await tokB.getAddress();

  // Watcher = admin (the local keeper signer). Lets the demo sweep without a separate service.
  await (await lk.connect(admin).setWatcher(admin.address)).wait();

  // Mint to owner (mock tokens). 1,000 DUSD and 50 DGOLD, both 18 decimals.
  await (await tokA.mint(owner.address, ethers.parseEther("1000"))).wait();
  await (await tokB.mint(owner.address, ethers.parseEther("50"))).wait();

  // Fund test wallets with native ETH from admin so they can pay gas for claim/sweep txs.
  for (const s of [owner, ben1, ben2]) {
    const bal = await ethers.provider.getBalance(s.address);
    if (bal < ethers.parseEther("50")) {
      await (await admin.sendTransaction({ to: s.address, value: ethers.parseEther("100") })).wait();
    }
  }

  // Owner registers a demo vault: 30-day interval, 0 grace, two beneficiaries 60/40, secret "demo-secret".
  const secret = "demo-secret";
  const secretHash = ethers.keccak256(ethers.toUtf8Bytes(secret));
  const lkOwner = lk.connect(owner);
  await (await lkOwner.register(30, 0, [ben1.address, ben2.address], [6000, 4000], secretHash, "0x00", { value: 0 })).wait();

  // Owner approves the token list on-chain (listed mode, the default) for tokA only. tokB stays unlisted.
  await (await tokA.connect(owner).approve(lkAddr, ethers.parseEther("1000"))).wait();
  await (await lkOwner.allowSweep(tokAAddr)).wait();

  // Read back vault id so the demo can print it.
  const data = await lk.attestationData(owner.address);
  const epoch = data.epoch;
  const vaultId = await lk.vaultIdOf(owner.address, epoch);
  const claimOpensAt = Number(data.claimOpensAt);

  const out = {
    network: "hardhat-local",
    chainId: 31338,
    rpc: "http://127.0.0.1:8545",
    lastKey: lkAddr,
    tokens: { DUSD: tokAAddr, DGOLD: tokBAddr },
    owner: owner.address,
    beneficiaries: [ben1.address, ben2.address],
    watcher: admin.address,
    vaultId,
    secret,
    claimOpensAt,
  };
  fs.writeFileSync(path.join(ROOT, "scripts", "local-demo.out.json"), JSON.stringify(out, null, 2));

  const cfg = `// Generated by scripts/local-demo.sh. Overrides frontend/config.js to the local hardhat chain.
// Do not commit. Delete this file to fall back to portaldot.
window.LASTKEY_CONFIG = {
  chainId: 31338,
  rpc: "http://127.0.0.1:8545",
  explorer: "http://127.0.0.1:8545",
  currency: { name: "ETH", symbol: "ETH", decimals: 18 },
  API_BASE: "http://127.0.0.1:8787",
  lastKeyAddress: "${lkAddr}",
};
`;
  fs.writeFileSync(path.join(ROOT, "frontend", "local-config.js"), cfg);

  console.log(JSON.stringify(out, null, 2));
}

main().catch((e) => {
  console.error(e);
  process.exitCode = 1;
});
